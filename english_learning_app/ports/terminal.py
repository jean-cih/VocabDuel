from typing import Protocol


class Terminal(Protocol):
    def wait_key(self, timeout: float | None) -> str | None: ...
    def wait_key_blinking(
        self,
        hint: str,
        timeout: float | None = None,
        interval: float = 0.5,
    ) -> str | None: ...
    def read_line(self, prompt: str = "") -> str: ...
    def hidden_cursor(self) -> None: ...
